class LanguageModel {
  final String code;
  final String enName;
  final String locName;
  final String flag;

  LanguageModel(this.code, this.enName, this.locName, this.flag);

  bool isEqual(LanguageModel other) {
    return enName == other.enName ||
        code == other.code ||
        locName == other.locName;
  }

  bool isOfCode(String otherCode) => code == otherCode;

  @override
  String toString() {
    return '${AppConst.kIsWeb ? code : flag} $locName';
  }
}

